/**
 * Функция showDetails
 * Выводит простое сообщение при нажатии на кнопку "Показать Детали".
 * В реальном магазине здесь могла бы быть сложная логика открытия модального окна.
 *
 * @param {string} productName - Название товара, для которого показываются детали.
 */
function showDetails(productName) {
    // Используем встроенное диалоговое окно для простоты.
    alert(`Вы запросили детали для товара: ${productName}. 
    
    Для оформления заказа, пожалуйста, перейдите в раздел "Контакты" и свяжитесь с нами!`);
    
    console.log(`Пользователь запросил детали: ${productName}`);
}

